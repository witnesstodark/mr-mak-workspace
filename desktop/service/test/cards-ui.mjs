// Runs only against an isolated Workspace and a local fake mobile transport.
import { expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { cp, mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createService } from '../server.mjs';
import { localDay } from '../workspace.mjs';
import { launchBrowser, desktopAuth } from './browser.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const sampleAssets = process.env.MRMAK_CARDS_SAMPLE_DIR || path.join(root, 'workspace/2026-09-15_my-dream-game/assets');
await mkdir(path.join(root, '.cache'), { recursive: true });
const repo = await mkdtemp(path.join(root, '.cache', 'cards-ui-'));
await cp(path.join(root, 'dist'), path.join(repo, 'ui'), { recursive: true });
await cp(path.join(root, 'public/assets'), path.join(repo, 'ui/assets'), { recursive: true });
await mkdir(path.join(repo, 'workspace/original'), { recursive: true });
const original = '<!doctype html><h1>Original custom report</h1>';
await writeFile(path.join(repo, 'workspace/original/report.html'), original);
await writeFile(path.join(repo, 'workspace/workspace.json'), JSON.stringify({ entities: [{ id: 'original', title: 'Original report', folder: 'original', type: 'standalone', category: 'dev', status: 'active', created: localDay(), steps: [{ name: 'Original', path: 'report.html' }] }] }));
const transport = { probe: async () => ({ installed: true, ready: true }), enable: async origin => ({ origin }), disable: async () => {} };
const service = await createService({ repo, uiDir: path.join(repo, 'ui'), mobileOptions: { transport }, mcpOptions: { home: repo, env: {} } });
let browser;
try {
  browser = await launchBrowser();
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  await desktopAuth(context, service.urls.workspace);
  await context.route('https://source.example/**', route => route.fulfill({ contentType: 'text/html', body: '<h1>Research source</h1>' }));
  const page = await context.newPage(); page.setDefaultTimeout(12000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(service.urls.workspace);
  await page.getByRole('button', { name: '+ New card', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'New Workspace card' });
  await dialog.getByLabel('Card title').fill('My editable board');
  await dialog.getByRole('button', { name: 'Create card', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My editable board', exact: true })).toBeVisible();
  const id = new URL(page.url()).hash.slice(2).split('/')[0];
  const registry = JSON.parse(await readFile(path.join(repo, 'workspace/workspace.json'), 'utf8'));
  const entity = registry.entities.find(item => item.id === id), cardFile = path.join(repo, 'workspace', entity.folder, 'content.card.json');
  await page.getByRole('button', { name: 'Add first entry' }).click();
  const entry = index => page.locator('.card-entry-editor').nth(index);
  await entry(0).getByLabel('Entry title', { exact: true }).fill('The gentleman');
  await entry(0).getByLabel('Notes').fill('A **readable silhouette** and one very important hat.');
  await entry(0).getByLabel('Prompt', { exact: true }).fill('Next iteration: simplify the hat and keep the small proportions.');
  await entry(0).locator('input[type=file]').setInputFiles(path.join(sampleAssets, 'c1_gentleman_gpt.webp'));
  await expect(entry(0).locator('.card-edit-image img')).toBeVisible();
  await page.getByRole('button', { name: '+ Add entry', exact: true }).click();
  await entry(1).getByLabel('Entry title', { exact: true }).fill('The sky islands');
  await entry(1).getByLabel('Notes').fill('Keep the route easy to read.\n\n- One landmark\n- One clear landing');
  await entry(1).getByLabel('Source URL', { exact: true }).fill('https://source.example/research');
  await entry(1).getByLabel('Link label', { exact: true }).fill('Research source');
  await entry(1).locator('input[type=file]').setInputFiles(path.join(sampleAssets, 's5_sky_islands_gpt.webp'));
  await expect(entry(1).locator('.card-edit-image img')).toBeVisible();
  await page.getByRole('button', { name: 'Move The sky islands up', exact: true }).click();
  await expect(entry(0).getByLabel('Entry title', { exact: true })).toHaveValue('The sky islands');
  const dragSource = page.getByRole('button', { name: 'Reorder The sky islands', exact: true });
  const dragTarget = page.getByRole('button', { name: 'Reorder The gentleman', exact: true });
  await dragSource.scrollIntoViewIfNeeded(); await dragTarget.scrollIntoViewIfNeeded();
  const from = await dragSource.boundingBox(), to = await dragTarget.boundingBox();
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
  await page.mouse.down();
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 10 });
  // A second move over the target delivers dragover in WebKit as well as Edge.
  await page.mouse.move(to.x + to.width / 2 + 2, to.y + to.height / 2);
  await page.mouse.up();
  await expect(entry(0).getByLabel('Entry title', { exact: true })).toHaveValue('The gentleman');
  await entry(1).getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('button', { name: 'Undo remove' }).click();
  await expect(page.locator('.card-entry-editor')).toHaveCount(2);
  // Navigation keeps an unsaved draft; the source is still the empty new card.
  await entry(0).getByLabel('Entry title', { exact: true }).fill('');
  await entry(0).getByLabel('Source URL', { exact: true }).fill('https://');
  await page.evaluate(() => { location.hash = '#/original'; });
  await page.frameLocator('iframe.report-frame').getByRole('heading', { name: 'Original custom report' }).waitFor();
  await page.evaluate(id => { location.hash = `#/${id}`; }, id);
  await expect(entry(0).getByLabel('Entry title', { exact: true })).toHaveValue('');
  await expect(entry(0).getByLabel('Source URL', { exact: true })).toHaveValue('https://');
  await entry(0).getByLabel('Entry title', { exact: true }).fill('The gentleman');
  await entry(0).getByLabel('Source URL', { exact: true }).fill('');
  assert.equal(JSON.parse(await readFile(cardFile, 'utf8')).items.length, 0);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('.card-save-status')).toHaveText('Saved');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(page.locator('.card-entry strong')).toContainText(['readable silhouette']);
  await page.locator('.card-prompt summary').click();
  await expect(page.locator('.card-prompt pre')).toHaveText(/simplify the hat/);
  await page.locator('.card-entry-image a').first().click();
  const lightbox = page.getByRole('dialog', { name: 'Image preview' }); await expect(lightbox).toBeVisible();
  const download = page.waitForEvent('download'); await lightbox.getByRole('button', { name: 'Download', exact: true }).click(); await download;
  await lightbox.getByRole('button', { name: 'Close', exact: true }).click();
  const popup = context.waitForEvent('page'); await page.getByRole('link', { name: 'Research source' }).click();
  const opened = await popup; await opened.waitForLoadState(); assert.equal(opened.url(), 'https://source.example/research'); await opened.close();
  for (const theme of ['dark', 'light']) {
    await page.evaluate(theme => { document.documentElement.dataset.workspaceTheme = theme; }, theme);
    for (const width of [1280, 768, 390]) {
      await page.setViewportSize({ width, height: 900 });
      await expect(page.getByRole('heading', { name: 'My editable board', exact: true })).toBeVisible();
      assert.equal(await page.locator('.editable-card').evaluate(node => node.scrollWidth <= node.clientWidth + 1), true);
      await page.locator('.editable-card').evaluate(node => { node.scrollTop = 0; });
      await page.screenshot({ path: path.join(repo, `gallery-${theme}-${width}.png`) });
      await page.getByRole('button', { name: 'Edit', exact: true }).click();
      assert.equal(await page.locator('.editable-card').evaluate(node => node.scrollWidth <= node.clientWidth + 1), true);
      await page.screenshot({ path: path.join(repo, `editor-${theme}-${width}.png`) });
      await page.getByRole('button', { name: 'Preview', exact: true }).click();
    }
  }
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('View', { exact: true }).selectOption('research');
  await page.getByRole('button', { name: 'Save', exact: true }).click(); await expect(page.locator('.card-save-status')).toHaveText('Saved');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(page.locator('.card-template-research')).toBeVisible();
  await page.screenshot({ path: path.join(repo, 'research-light-1280.png') });
  // Simulate an agent edit while a human has an unsaved draft.
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await entry(0).getByLabel('Notes').fill('My unsaved notes');
  const agent = JSON.parse(await readFile(cardFile, 'utf8')); agent.items[0].body = 'Updated by an agent';
  await writeFile(cardFile, JSON.stringify(agent, null, 2) + '\n');
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(page.locator('.card-conflict')).toBeVisible({ timeout: 10000 });
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeDisabled();
  await expect(entry(0).getByLabel('Notes')).toHaveValue('My unsaved notes');
  assert.equal(JSON.parse(await readFile(cardFile, 'utf8')).items[0].body, 'Updated by an agent');
  await page.getByText('Review latest version', { exact: true }).click();
  await expect(page.locator('.card-conflict .card-content')).toContainText('Updated by an agent');
  await page.getByRole('button', { name: 'Discard my draft and load latest' }).click();
  await expect(entry(0).getByLabel('Notes')).toHaveValue('Updated by an agent');
  // A failed save must retain the form and never claim success.
  await entry(0).getByLabel('Notes').fill('Retry this edit');
  await page.route(`**/api/workspace/cards/${id}/0`, route => route.request().method() === 'PUT' ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Fixture save unavailable.' }) }) : route.continue());
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Fixture save unavailable.');
  await expect(entry(0).getByLabel('Notes')).toHaveValue('Retry this edit');
  await page.unroute(`**/api/workspace/cards/${id}/0`);
  await page.getByRole('button', { name: 'Save', exact: true }).click(); await expect(page.locator('.card-save-status')).toHaveText('Saved');
  await page.reload(); await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(entry(0).getByLabel('Notes')).toHaveValue('Retry this edit');
  // A background read that started before Save must not restore the older copy.
  let releaseRead, readCaptured;
  const readGate = new Promise(resolve => { releaseRead = resolve; });
  const captured = new Promise(resolve => { readCaptured = resolve; });
  let held = false;
  await page.route(`**/api/workspace/cards/${id}/0`, async route => {
    if (route.request().method() !== 'GET' || held) return route.continue();
    held = true;
    const response = await route.fetch(); readCaptured();
    await readGate; await route.fulfill({ response });
  });
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await captured;
  await entry(0).getByLabel('Notes').fill('Latest saved notes');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('.card-save-status')).toHaveText('Saved');
  const returnedRead = page.waitForResponse(response => response.url().endsWith(`/api/workspace/cards/${id}/0`) && response.request().method() === 'GET');
  releaseRead(); await returnedRead;
  await expect(entry(0).getByLabel('Notes')).toHaveValue('Latest saved notes');
  await page.unroute(`**/api/workspace/cards/${id}/0`);
  // Exercise the actual paired-phone UI without touching the user's Tailscale.
  await service.mobile.enable();
  const qr = await service.mobile.newPairing();
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const phone = await mobileContext.newPage(); phone.on('pageerror', error => errors.push(error.message));
  const token = new URL(qr.url).hash.slice(6);
  const pendingResponse = await mobileContext.request.post(`${service.mobile.origin}/mobile/api/pair`, { data: { token, name: 'Card preview phone' }, headers: { Origin: service.mobile.origin } });
  const pending = await pendingResponse.json(); await service.mobile.approve(pending.id);
  const paired = await mobileContext.request.post(`${service.mobile.origin}/mobile/api/pair/finish`, { data: pending, headers: { Origin: service.mobile.origin } });
  assert.equal(paired.status(), 200);
  await phone.goto(`${service.mobile.origin}/mobile/`);
  await phone.getByRole('button', { name: 'Results', exact: true }).click();
  await phone.getByRole('button', { name: /My editable board/ }).click();
  await expect(phone.locator('.mobile-report-card')).toContainText('Latest saved notes');
  assert.equal(await phone.getByRole('button', { name: 'Edit', exact: true }).count(), 0);
  assert.equal(await phone.locator('.mobile-report-card').evaluate(node => node.scrollWidth <= node.clientWidth + 1), true);
  await phone.locator('.card-entry-image a').first().click(); await expect(phone.getByRole('dialog', { name: 'Image preview' })).toBeVisible();
  await phone.getByRole('button', { name: 'Close', exact: true }).click();
  await phone.screenshot({ path: path.join(repo, 'phone-card-390.png') });
  assert.equal(await readFile(path.join(repo, 'workspace/original/report.html'), 'utf8'), original);
  assert.deepEqual(errors, []);
  console.log(`Editable cards passed: create, form editing, Markdown, upload, drag/keyboard reorder, undo, draft recovery, save/reload, conflict recovery, failed saves, images/downloads, external links, dark/light 390/768/1280 layouts and paired mobile preview. Screenshots: ${repo}`);
} finally { await browser?.close(); await service.close(); }
